const {
  resolveSchemaFields,
  resolveTableName
} = require("./schemaCompaction");

// Example rows for one table. These are what SDV learns from, so their realism
// is the ceiling on everything downstream - SDV can only reproduce patterns that
// are already present here.
//
// Two decisions worth knowing about:
//
// 1. Every column except a declared primary key is requested, including columns
//    that will later turn out to be foreign keys. Seeds are generated at upload
//    time, and relationships are not inferred until the user clicks Generate
//    Tables, so there is no way to know which columns are foreign keys yet.
//    Generating them and discarding them later is the only ordering that works.
//
// 2. Rows are requested in small batches with a different instruction each time.
//    Asked for 300 rows in one response a model produces roughly 40 distinct
//    ones and then starts repeating itself, and SDV trained on that learns "all
//    rows look the same" - the exact problem this migration exists to fix.

// Deliberately domain-neutral. A hospital schema and a retail schema both need
// their seed rows spread across time, volume and category, and neither needs
// instructions written specifically for it.
const SEGMENT_INSTRUCTIONS = [
  "Cover the most ordinary, everyday cases. These should look like the bulk of the table.",
  "Use different locations, categories or groupings than a typical batch would. Push for variety in the descriptive columns.",
  "Cover high-value, high-volume or high-activity cases. Numeric columns should sit at the upper end of what is realistic.",
  "Cover low-value, small or minimal cases. Numeric columns should sit at the lower end of what is realistic.",
  "Cover the earliest time period that is plausible for this data. Date columns should be older than in other batches.",
  "Cover the most recent time period. Date columns should be recent, and the mix should reflect how this data looks today.",
  "Cover unusual but entirely legitimate cases - rare categories, uncommon combinations, edge values that still obey every rule.",
  "Cover mid-range cases that sit between the extremes, with a different mix of categories again."
];

function getSegmentInstruction(batchIndex) {
  return SEGMENT_INSTRUCTIONS[batchIndex % SEGMENT_INSTRUCTIONS.length];
}

function describeField(field) {
  const parts = [`${field.name} (${field.type})`];

  if (field.type === "enum") {
    const values = field.options?.values || field.options || [];

    if (Array.isArray(values) && values.length) {
      parts.push(`must be exactly one of: ${values.map((value) => JSON.stringify(value)).join(", ")}`);
    }
  }

  const min = field.min ?? field.options?.min;
  const max = field.max ?? field.options?.max;

  if (min !== undefined && min !== null) parts.push(`minimum ${min}`);
  if (max !== undefined && max !== null) parts.push(`maximum ${max}`);

  if (field.notNull) parts.push("never null");
  if (field.unique) parts.push("every value different");

  return `  - ${parts.join(", ")}`;
}

// A declared primary key is generated by our own code with a counter, never by
// the model and never by SDV, so asking for it wastes output tokens on values
// that are discarded.
//
// UUID columns are skipped for the same reason. Point 1 above explains that a
// non-key UUID is almost always a foreign key whose real value is assigned at
// Generate Tables once relationships are known - so the model's value is thrown
// away regardless. Asking for it anyway was actively harmful: a model cannot
// reliably emit the version and variant nibbles a strict UUID check requires, and
// on a table with several UUID columns those independent failures multiply until
// most rows are dropped and the batch is rejected. There is also nothing for SDV
// to learn from a random identifier.
function isUuidField(field) {
  return String(field?.type || "").toLowerCase() === "uuid";
}

function getRequestedFields(schema) {
  return resolveSchemaFields(schema).filter((field) => {
    const isPrimaryKey = field?.primaryKey === true || field?.primary_key === true;

    return field?.name && !isPrimaryKey && !isUuidField(field);
  });
}

const TYPE_RULES = `TYPE RULES

- string: plain text. Realistic for the column name, not lorem ipsum.
- number: a bare number. No currency symbols, no thousands separators, no quotes.
- boolean: true or false, unquoted.
- date: "YYYY-MM-DD" only.
- email: a valid address. Make it consistent with any name column in the same row.
- enum: exactly one of the listed values, copied character for character.
- address: a street address as a single line of text.`;

function buildSeedRowsPrompt(input = {}) {
  const { schema, rowsPerBatch, batchIndex = 0, totalBatches = 1 } = input;

  const tableName = resolveTableName(schema);
  const fields = getRequestedFields(schema);

  return `You are generating realistic sample data for a table called "${tableName}".

COLUMNS

${fields.map(describeField).join("\n")}

YOUR TASK

Return exactly ${rowsPerBatch} rows.

This is batch ${batchIndex + 1} of ${totalBatches}. ${getSegmentInstruction(batchIndex)}

WHAT MAKES THESE ROWS USEFUL

These rows are used to learn the statistical patterns of this table, so the
relationships between columns matter more than any single value.

- Values in the same row must agree with each other. A city must sit in its own
  country. An email should match its own name column. A total should be
  consistent with the quantity and price in that same row.
- Dates in the same row must be in a sensible order. Anything describing an end,
  a delivery or a completion must come after its matching start or order date.
- Let the numbers vary the way real data varies. Do not repeat the same value, and
  do not space values out evenly.
- Where a category plausibly drives a number, let it. If this table has tiers,
  sizes or grades, the numeric columns should differ across them in a way that
  makes sense for what this table describes.
- Make every row different from the others in this batch.

${TYPE_RULES}

OUTPUT FORMAT

Return exactly one valid JSON object with this shape and no other properties:

{
  "rows": [
    {
${fields.map((field) => `      ${JSON.stringify(field.name)}: <value>`).join(",\n")}
    }
  ]
}

Every row must contain every column listed above. Use the column names exactly as
spelled. Return only the JSON object. No markdown, no explanation, no commentary.`;
}

// Repair asks for a targeted fix. Resending the full prompt with an error
// appended tends to make smaller models rewrite the parts that were already
// correct, so the specific complaint leads here.
function buildSeedRowsRepairPrompt(basePrompt, errorMessage) {
  return `${basePrompt}

PREVIOUS ATTEMPT WAS REJECTED

${errorMessage}

Return the complete corrected JSON object with the full set of rows. Fix only
what the rejection describes and keep everything else the same.`;
}

module.exports = {
  buildSeedRowsPrompt,
  buildSeedRowsRepairPrompt,
  getRequestedFields,
  SEGMENT_INSTRUCTIONS
};